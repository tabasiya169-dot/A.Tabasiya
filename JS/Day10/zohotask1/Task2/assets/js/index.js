// Explicit return
const add = (a, b) => {
    return a + b;
};

console.log(add(10, 20));


// Implicit return
const addImplicit = (a, b) => a + b;

console.log(addImplicit(10, 20));


// Explicit return
const square = (n) => {
    return n * n;
};

console.log(square(5));


// Implicit return
const squareImplicit = (n) => n * n;

console.log(squareImplicit(5));